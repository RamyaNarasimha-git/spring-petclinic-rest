CREATE TABLE video_consultation_bookings (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id VARCHAR(64) NOT NULL UNIQUE,
  pet_id INT NOT NULL,
  owner_id INT NOT NULL,
  vet_id INT,
  severity VARCHAR(16) NOT NULL,
  triage_priority INT NOT NULL,
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP NOT NULL,
  status VARCHAR(16) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  version INT
);

CREATE INDEX idx_vcb_triage ON video_consultation_bookings (triage_priority DESC, created_at ASC);
CREATE INDEX idx_vcb_vet_time ON video_consultation_bookings (vet_id, start_time, end_time);
CREATE INDEX idx_vcb_pet ON video_consultation_bookings (pet_id);

CREATE TABLE video_consultation_slots (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id INT NOT NULL,
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP NOT NULL,
  capacity INT NOT NULL,
  booked INT NOT NULL,
  version INT,
  CONSTRAINT uk_video_slot_vet_window UNIQUE (vet_id, start_time, end_time)
);
